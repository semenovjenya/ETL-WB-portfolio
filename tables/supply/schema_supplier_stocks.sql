CREATE SCHEMA IF NOT EXISTS supply;
CREATE SCHEMA IF NOT EXISTS reports;

DO $$
BEGIN
    IF to_regclass('reports.wb_supplier_stocks') IS NOT NULL
       AND to_regclass('supply.wb_supplier_stocks') IS NULL THEN
        EXECUTE 'ALTER TABLE reports.wb_supplier_stocks SET SCHEMA supply';
    END IF;
END $$;

DO $$
BEGIN
    IF to_regclass('reports.wb_supplier_stocks_progress') IS NOT NULL AND to_regclass('supply.wb_supplier_stocks_progress') IS NULL THEN
        EXECUTE 'ALTER TABLE reports.wb_supplier_stocks_progress SET SCHEMA supply';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS supply.wb_supplier_stocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME supply.wb_supplier_stocks_daily_id_seq
    ),
    snapshot_date DATE NOT NULL,
    last_change_date TIMESTAMP WITH TIME ZONE NOT NULL,
    warehouse_name VARCHAR(255) NOT NULL,
    supplier_article VARCHAR(255),
    nm_id BIGINT,
    barcode VARCHAR(255) NOT NULL,
    quantity INTEGER DEFAULT 0,
    in_way_to_client INTEGER DEFAULT 0,
    in_way_from_client INTEGER DEFAULT 0,
    quantity_full INTEGER DEFAULT 0,
    category VARCHAR(500),
    subject VARCHAR(500),
    brand VARCHAR(255),
    tech_size VARCHAR(100),
    price DECIMAL(12, 2),
    discount DECIMAL(5, 2),
    is_supply BOOLEAN,
    is_realization BOOLEAN,
    sc_code VARCHAR(100),
    last_synced_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT wb_supplier_stocks_daily_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS supply.wb_supplier_stocks_progress (
    id SERIAL PRIMARY KEY,
    last_change_date_from TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_wb_supplier_stocks_snapshot_date_key
    ON supply.wb_supplier_stocks (barcode, warehouse_name, snapshot_date);

CREATE INDEX IF NOT EXISTS idx_wb_supplier_stocks_daily_snapshot_date
    ON supply.wb_supplier_stocks(snapshot_date);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_stocks_daily_nm_id
    ON supply.wb_supplier_stocks(nm_id);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_stocks_daily_warehouse
    ON supply.wb_supplier_stocks(warehouse_name);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_stocks_daily_last_change
    ON supply.wb_supplier_stocks(last_change_date);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_stocks_daily_last_synced
    ON supply.wb_supplier_stocks(last_synced_at);

COMMENT ON TABLE supply.wb_supplier_stocks IS
'Daily source table for supplier/stocks.';

CREATE OR REPLACE VIEW supply.v_wb_supplier_stocks_latest_daily AS
WITH snapshot_dates AS (
    SELECT DISTINCT snapshot_date
    FROM supply.wb_supplier_stocks
),
ranked AS (
    SELECT
        d.snapshot_date AS effective_snapshot_date,
        s.*,
        ROW_NUMBER() OVER (
            PARTITION BY d.snapshot_date, s.barcode, s.warehouse_name
            ORDER BY s.snapshot_date DESC, s.id DESC
        ) AS rn
    FROM snapshot_dates d
    JOIN supply.wb_supplier_stocks s
      ON s.snapshot_date <= d.snapshot_date
)
SELECT
    id,
    last_change_date,
    warehouse_name,
    supplier_article,
    nm_id,
    barcode,
    quantity,
    in_way_to_client,
    in_way_from_client,
    quantity_full,
    category,
    subject,
    brand,
    tech_size,
    price,
    discount,
    is_supply,
    is_realization,
    sc_code,
    last_synced_at,
    effective_snapshot_date AS snapshot_date
FROM ranked
WHERE rn = 1;

CREATE OR REPLACE VIEW supply.v_wb_supplier_stocks_latest_snapshot AS
WITH cutoff AS (
    SELECT MAX(snapshot_date) AS snapshot_date
    FROM supply.wb_supplier_stocks
),
ranked AS (
    SELECT
        c.snapshot_date AS effective_snapshot_date,
        s.*,
        ROW_NUMBER() OVER (
            PARTITION BY s.barcode, s.warehouse_name
            ORDER BY s.snapshot_date DESC, s.id DESC
        ) AS rn
    FROM cutoff c
    JOIN supply.wb_supplier_stocks s
      ON s.snapshot_date <= c.snapshot_date
)
SELECT
    id,
    last_change_date,
    warehouse_name,
    supplier_article,
    nm_id,
    barcode,
    quantity,
    in_way_to_client,
    in_way_from_client,
    quantity_full,
    category,
    subject,
    brand,
    tech_size,
    price,
    discount,
    is_supply,
    is_realization,
    sc_code,
    last_synced_at,
    effective_snapshot_date AS snapshot_date
FROM ranked
WHERE rn = 1;
