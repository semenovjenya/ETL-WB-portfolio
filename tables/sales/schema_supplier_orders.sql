CREATE SCHEMA IF NOT EXISTS sales;
CREATE SCHEMA IF NOT EXISTS reports;

DO $$
BEGIN
    IF to_regclass('reports.wb_supplier_orders') IS NOT NULL
       AND to_regclass('sales.wb_supplier_orders') IS NULL THEN
        EXECUTE 'ALTER TABLE reports.wb_supplier_orders SET SCHEMA sales';
    END IF;
END $$;

DO $$
BEGIN
    IF to_regclass('reports.wb_supplier_orders_progress') IS NOT NULL AND to_regclass('sales.wb_supplier_orders_progress') IS NULL THEN
        EXECUTE 'ALTER TABLE reports.wb_supplier_orders_progress SET SCHEMA sales';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS sales.wb_supplier_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME sales.wb_supplier_orders_daily_id_seq
    ),
    snapshot_date DATE NOT NULL,
    date_ord TIMESTAMP WITH TIME ZONE,
    last_change_date TIMESTAMP WITH TIME ZONE NOT NULL,
    warehouse_name VARCHAR(255),
    warehouse_type VARCHAR(255),
    country_name VARCHAR(255),
    oblast_okrug_name VARCHAR(255),
    region_name VARCHAR(255),
    supplier_article VARCHAR(255),
    nm_id BIGINT,
    barcode VARCHAR(255),
    category VARCHAR(500),
    subject VARCHAR(500),
    brand VARCHAR(255),
    tech_size VARCHAR(100),
    income_id BIGINT,
    is_supply BOOLEAN,
    is_realization BOOLEAN,
    total_price DECIMAL(12, 2),
    discount_percent DECIMAL(5, 2),
    spp DECIMAL(5, 2),
    finished_price DECIMAL(12, 2),
    price_with_disc DECIMAL(12, 2),
    is_cancel BOOLEAN,
    cancel_date TIMESTAMP WITH TIME ZONE,
    sticker VARCHAR(255),
    g_number VARCHAR(255),
    srid VARCHAR(500) NOT NULL,
    last_synced_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT wb_supplier_orders_daily_pkey PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS sales.wb_supplier_orders_progress (
    id SERIAL PRIMARY KEY,
    last_change_date_from TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_wb_supplier_orders_snapshot_date_key
    ON sales.wb_supplier_orders (srid, snapshot_date);

CREATE INDEX IF NOT EXISTS idx_wb_supplier_orders_daily_snapshot_date
    ON sales.wb_supplier_orders(snapshot_date);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_orders_daily_nm_id
    ON sales.wb_supplier_orders(nm_id);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_orders_daily_last_change
    ON sales.wb_supplier_orders(last_change_date);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_orders_daily_srid
    ON sales.wb_supplier_orders(srid);

COMMENT ON TABLE sales.wb_supplier_orders IS
'Daily source table for supplier/orders.';

CREATE OR REPLACE VIEW sales.v_wb_supplier_orders_latest_daily AS
WITH ranked AS (
    SELECT
        o.*,
        ROW_NUMBER() OVER (
            PARTITION BY COALESCE(o.date_ord::date, o.snapshot_date), o.srid
            ORDER BY o.snapshot_date DESC, o.id DESC
        ) AS rn
    FROM sales.wb_supplier_orders o
)
SELECT *
FROM ranked
WHERE rn = 1;

CREATE OR REPLACE VIEW sales.v_wb_supplier_orders_latest_snapshot AS
WITH ranked AS (
    SELECT
        o.*,
        ROW_NUMBER() OVER (
            PARTITION BY o.srid
            ORDER BY o.snapshot_date DESC, o.id DESC
        ) AS rn
    FROM sales.wb_supplier_orders o
)
SELECT *
FROM ranked
WHERE rn = 1;
