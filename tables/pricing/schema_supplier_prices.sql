CREATE SCHEMA IF NOT EXISTS pricing;
CREATE SCHEMA IF NOT EXISTS reports;

DO $$
BEGIN
    IF to_regclass('reports.wb_supplier_prices') IS NOT NULL
       AND to_regclass('pricing.wb_supplier_prices') IS NULL THEN
        EXECUTE 'ALTER TABLE reports.wb_supplier_prices SET SCHEMA pricing';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS pricing.wb_supplier_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (
        SEQUENCE NAME pricing.wb_supplier_prices_daily_id_seq
    ),
    snapshot_date DATE NOT NULL,
    nm_id BIGINT NOT NULL,
    vendor_code VARCHAR(255),
    currency_iso_code VARCHAR(10),
    discount DECIMAL(5, 2),
    club_discount DECIMAL(5, 2),
    editable_size_price BOOLEAN,
    is_bad_turnover BOOLEAN,
    price DECIMAL(12, 2),
    discounted_price DECIMAL(12, 2),
    club_discounted_price DECIMAL(12, 2),
    sizes_json JSONB,
    last_synced_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT wb_supplier_prices_daily_pkey PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_wb_supplier_prices_snapshot_date_key
    ON pricing.wb_supplier_prices (nm_id, snapshot_date);

CREATE INDEX IF NOT EXISTS idx_wb_supplier_prices_daily_snapshot_date
    ON pricing.wb_supplier_prices(snapshot_date);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_prices_daily_nm_id
    ON pricing.wb_supplier_prices(nm_id);
CREATE INDEX IF NOT EXISTS idx_wb_supplier_prices_daily_last_synced
    ON pricing.wb_supplier_prices(last_synced_at);

COMMENT ON TABLE pricing.wb_supplier_prices IS
'Daily source table for supplier prices.';

CREATE OR REPLACE VIEW pricing.v_wb_supplier_prices_latest_daily AS
SELECT *
FROM pricing.wb_supplier_prices;

CREATE OR REPLACE VIEW pricing.v_wb_supplier_prices_latest_snapshot AS
SELECT *
FROM pricing.wb_supplier_prices
WHERE snapshot_date = (
    SELECT MAX(snapshot_date)
    FROM pricing.wb_supplier_prices
);
